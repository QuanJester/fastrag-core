"""FastAPI routes for search and SSE streaming query generation."""

import asyncio
import json
import time
from fastapi import APIRouter
from fastapi.responses import StreamingResponse
from src.api.schemas import SearchRequest, SearchResponse, AskRequest, AskResponse, DocumentResult

router = APIRouter()


@router.post("/search", response_model=SearchResponse, summary="Hybrid Search with Cache")
async def search(request: SearchRequest):
    start_time = time.perf_counter()

    # Placeholder retrieval response
    mock_results = [
        DocumentResult(
            id=f"doc_{i}",
            content=f"Sample retrieved content for query: '{request.query}' (Rank {i+1})",
            score=round(1.0 / (i + 1), 4),
            metadata={"source": "fastrag-corpus"},
        )
        for i in range(request.top_k)
    ]

    latency_ms = (time.perf_counter() - start_time) * 1000
    return SearchResponse(
        query=request.query,
        results=mock_results,
        cached=False,
        latency_ms=round(latency_ms, 2),
    )


@router.post("/ask", summary="Ask query with optional SSE streaming")
async def ask(request: AskRequest):
    if request.stream:
        async def event_generator():
            words = f"This is an SSE streamed answer for: '{request.query}' generated by FastRAG.".split()
            for word in words:
                await asyncio.sleep(0.05)
                yield f"data: {json.dumps({'delta': word + ' '})}\n\n"
            yield f"data: {json.dumps({'done': True})}\n\n"

        return StreamingResponse(event_generator(), media_type="text/event-stream")

    return AskResponse(
        query=request.query,
        answer=f"Synthesized response for: '{request.query}'.",
        sources=[],
        latency_ms=12.5,
    )
